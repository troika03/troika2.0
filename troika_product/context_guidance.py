def capability_guidance(capability: str, *, device: bool) -> str:
    if capability == "assistant":
        return ASSISTANT_GUIDANCE
    if capability in {"files", "documents", "development"}:
        return DEVICE_FILE_GUIDANCE if device else SERVER_FILE_GUIDANCE
    if capability == "web":
        return WEB_GUIDANCE
    if capability == "phone":
        return DEVICE_ROUTING_GUIDANCE
    return ""
